const FA_DIGITS = ["۰", "۱", "۲", "۳", "۴", "۵", "۶", "۷", "۸", "۹"];
function toFaDigits(n) {
  return String(n).replace(/\d/g, (d) => FA_DIGITS[d]);
}
function formatNumber(n, lang) {
  const v = Number(n).toLocaleString("en-US");
  return lang === "fa" ? toFaDigits(v) : v;
}
function formatPrice(n, lang) {
  if (lang === "fa") return `${toFaDigits(Number(n).toLocaleString("fa-IR"))} تومان`;
  const usd = Math.max(1, Math.round(Number(n) / 62000));
  return `$${usd.toLocaleString("en-US")}`;
}
